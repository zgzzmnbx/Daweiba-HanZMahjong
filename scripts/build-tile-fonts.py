#!/usr/bin/env python3
"""Build self-hosted, static 600-weight Noto Sans SC subsets. Requires fonttools 4.60.2 and Brotli 1.1.0."""
import argparse,copy,hashlib,json,re,shutil
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,required=True);a=p.parse_args()
source=a.source/'NotoSansSC[wght].ttf';digest=hashlib.sha256(source.read_bytes()).hexdigest()
assert digest=='a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da','Unexpected source font'
font=instantiateVariableFont(TTFont(source),{'wght':600},inplace=True)
for key,value in {1:'Hanz Tile Sans',2:'SemiBold',3:'HanzTileSans-600-1',4:'Hanz Tile Sans SemiBold',6:'HanzTileSans-SemiBold',16:'Hanz Tile Sans',17:'SemiBold'}.items():
 for platform,encoding,language in [(3,1,1033),(1,0,0)]:font['name'].setName(value,key,platform,encoding,language)
cmap=font.getBestCmap();all_codes=set(cmap)
core_file=root/'scripts/tile-font-core.txt'
if core_file.exists():core={int(x,16) for x in core_file.read_text().split()}
else:
 core=set(range(32,127))|set(range(0x3000,0x3040))|{0xff0c,0xff1f,0xff01}
 for directory in ['apps/web/src','apps/server','packages']:
  for path in (root/directory).rglob('*'):
   if path.suffix in {'.ts','.tsx','.json'}:core|={ord(c) for c in path.read_text() if ord(c)>=0x2e80}
 core &= all_codes;core_file.write_text('\n'.join(f'{c:X}' for c in sorted(core))+'\n')
assert core<=all_codes
chunks={'core':core}
for c in sorted(all_codes-core):chunks.setdefault(f'u{c//4096:03x}',set()).add(c)
out=root/'apps/web/public/fonts';out.mkdir(parents=True,exist_ok=True)
shutil.copy2(a.source/'OFL.txt',out/'OFL-NotoSansSC.txt')
def ranges(codes):
 result=[];start=last=None
 for c in sorted(codes):
  if last is not None and c==last+1:last=c;continue
  if last is not None:result.append(f'U+{start:X}'+(f'-{last:X}' if last!=start else ''))
  start=last=c
 if last is not None:result.append(f'U+{start:X}'+(f'-{last:X}' if last!=start else ''))
 return ','.join(result)
records=[];css=['/* Generated by scripts/build-tile-fonts.py; Noto Sans SC, SIL OFL 1.1. */']
for name,codes in chunks.items():
 f=copy.deepcopy(font);options=subset.Options();options.name_IDs=['*'];options.name_legacy=True;options.name_languages=['*'];options.recalc_timestamp=False
 s=subset.Subsetter(options=options);s.populate(unicodes=codes);s.subset(f);f.flavor='woff2';temp=out/(name+'.woff2');f.save(temp)
 data=temp.read_bytes();sha=hashlib.sha256(data).hexdigest();filename=f'hanz-tile-600-{name}-{sha[:10]}.woff2';temp.rename(out/filename)
 check=TTFont(out/filename);assert set(check.getBestCmap())==codes
 records.append({'file':filename,'bytes':len(data),'sha256':sha,'codepoints':len(codes),'unicodeRange':ranges(codes)})
 css.append('@font-face{font-family:"Hanz Tile Sans";font-style:normal;font-weight:600;font-display:swap;src:url("/fonts/'+filename+'") format("woff2");unicode-range:'+ranges(codes)+'}')
 print(name,len(codes),len(data),flush=True)
(root/'apps/web/src/tile-font-faces.css').write_text('\n'.join(css)+'\n')
manifest={'family':'Hanz Tile Sans','weight':600,'source':json.loads((a.source/'source.json').read_text()),'license':'SIL Open Font License 1.1','modifications':'Static weight 600; renamed to Hanz Tile Sans; disjoint Unicode WOFF2 subsets, no glyph outlines changed beyond weight instancing.','codepoints':len(all_codes),'core':len(core),'subsets':records}
(out/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
html=root/'apps/web/index.html';text=html.read_text();tag='<link rel="preload" href="/fonts/'+records[0]['file']+'" as="font" type="font/woff2" crossorigin/>'
text=re.sub(r'<link rel="preload" href="/fonts/[^"]+" as="font" type="font/woff2" crossorigin/>','',text)
html.write_text(text.replace('</head>',tag+'</head>'))
print('Total',len(all_codes),sum(r['bytes'] for r in records),flush=True)
