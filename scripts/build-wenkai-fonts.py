#!/usr/bin/env python3
"""Reproducible original LXGW WenKai v1.530 Medium subsets; no outline/name changes."""
import argparse,copy,hashlib,io,json,zipfile,re
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset
p=argparse.ArgumentParser();p.add_argument('--zip',type=Path,required=True);p.add_argument('--root',type=Path,required=True);a=p.parse_args()
out=a.root/'apps/web/public/fonts/wenkai';out.mkdir(parents=True,exist_ok=True)
with zipfile.ZipFile(a.zip) as z:
 entry='lxgw-wenkai-v1.530/LXGWWenKai-Medium.ttf';data=z.read(entry);license=z.read('lxgw-wenkai-v1.530/OFL.txt')
assert hashlib.sha256(data).hexdigest()=='f4b8a34d1f838fe411540cb7c97b1c384ac9738a876c4104500bc42508b2312a', 'Unexpected original Medium source'
assert hashlib.sha256(a.zip.read_bytes()).hexdigest()=='1644a3f88f84b9627c1b00e3e41c5752ef1bdea0dec2ac3a024bf107a7bd149e', 'Unexpected source archive'
f=TTFont(io.BytesIO(data));assert f['OS/2'].usWeightClass==500
codes=set(f.getBestCmap());core={int(x,16) for x in (a.root/'scripts/pingfang-font-core.txt').read_text().split()}|set(map(ord,'一人口赢藏警未末己已巳，。字间胡牌天书摸打吃'))
assert core<=codes, sorted(core-codes)
chunks={'core':core}
for c in sorted(codes-core):chunks.setdefault(f'u{c//1024:03x}',set()).add(c)
def ranges(chars):
 result=[];start=last=None
 for c in sorted(chars):
  if last is not None and c==last+1:last=c;continue
  if last is not None:result.append(f'U+{start:X}'+(f'-{last:X}' if last!=start else ''))
  start=last=c
 if last is not None:result.append(f'U+{start:X}'+(f'-{last:X}' if last!=start else ''))
 return ','.join(result)
records=[];css=[]
for name,chars in chunks.items():
 font=copy.deepcopy(f);options=subset.Options();options.name_IDs=['*'];options.name_legacy=True;options.name_languages=['*'];options.recalc_timestamp=False
 s=subset.Subsetter(options=options);s.populate(unicodes=chars);s.subset(font);font.flavor='woff2';buf=io.BytesIO();font.save(buf);b=buf.getvalue();sha=hashlib.sha256(b).hexdigest();file=f'wenkai-500-{name}-{sha[:10]}.woff2';(out/file).write_bytes(b)
 assert set(TTFont(io.BytesIO(b)).getBestCmap())==chars
 records.append({'file':file,'sha256':sha,'bytes':len(b),'codepoints':len(chars),'unicodeRange':ranges(chars)})
 css.append('@font-face{font-family:"Hanz WenKai";font-style:normal;font-weight:500;font-display:swap;src:url("/fonts/wenkai/'+file+'") format("woff2");unicode-range:'+ranges(chars)+'}')
 print(name,len(chars),len(b),flush=True)
(out/'OFL.txt').write_bytes(license)
(out/'manifest.json').write_text(json.dumps({'family':'Hanz WenKai','version':'1.530','weight':500,'sourcePackage':a.zip.name,'sourcePackageSha256':hashlib.sha256(a.zip.read_bytes()).hexdigest(),'sourceFile':entry,'sourceFileSha256':hashlib.sha256(data).hexdigest(),'sourceBytes':len(data),'originalFamily':f['name'].getDebugName(1),'postscriptName':f['name'].getDebugName(6),'fontRevision':f['head'].fontRevision,'codepoints':len(codes),'preloads':[r['file'] for r in records if '-core-' in r['file']],'subsets':records},ensure_ascii=False,indent=2)+'\n')
(a.root/'apps/web/src/wenkai-faces.css').write_text('/* Original LXGW WenKai Medium v1.530; generated by scripts/build-wenkai-fonts.py. */\n'+'\n'.join(css)+'\n')
print('TOTAL',len(records),sum(r['bytes'] for r in records))

html=a.root/'apps/web/index.html'
s=re.sub(r'<link rel="preload" href="/fonts/wenkai/[^"]+" as="font" type="font/woff2" crossorigin/>','',html.read_text())
tag='<link rel="preload" href="/fonts/wenkai/'+records[0]['file']+'" as="font" type="font/woff2" crossorigin/>'
html.write_text(s.replace('</head>',tag+'</head>'))
